// 역 좌표 (위도, 경도) — 서버 STATIONS 목록과 이름 기준으로 대응
// KTX/SRT 정차역 실제 위치 근사값. 지도 표시 전용이라 정밀도는 이 수준이면 충분하다.
// 두 역 사이를 살짝 휘는 곡선(베지어)으로 잇는다 — 직선보다 경로 느낌이 산다.
// 지도 구현(네이버/Leaflet)과 무관한 순수 좌표 계산이라 여기 둔다.
export function routeArc(a: [number, number], b: [number, number], steps = 48, bend = 0.18): [number, number][] {
  const dLat = b[0] - a[0];
  const dLng = b[1] - a[1];
  // 중점에서 수직 방향으로 밀어낸 베지어 제어점
  const c: [number, number] = [(a[0] + b[0]) / 2 - dLng * bend, (a[1] + b[1]) / 2 + dLat * bend];
  const pts: [number, number][] = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    pts.push([
      (1 - t) ** 2 * a[0] + 2 * (1 - t) * t * c[0] + t ** 2 * b[0],
      (1 - t) ** 2 * a[1] + 2 * (1 - t) * t * c[1] + t ** 2 * b[1],
    ]);
  }
  return pts;
}

