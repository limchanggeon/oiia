"""한국 명절·공휴일 표 (음력 기준일 고정).

LLM은 음력 명절 날짜를 매번 다르게 추측한다(검증 중 '설 전날'이 2027-02-05 ↔ 2027-02-16으로
흔들림). FR-2의 "설 전날" 같은 발화를 신뢰성 있게 처리하려면 근거 날짜를 프롬프트에 주입해야 한다.

유지보수: 매년 초에 다음 2년치를 확인해 갱신한다 (설날·추석은 음력이라 매년 양력 날짜가 바뀜).
"""
import datetime as dt
from typing import Dict, List

# 확인 기준: 한국천문연구원 음양력 (설날=음력 1/1, 추석=음력 8/15)
HOLIDAYS: Dict[str, str] = {
    "2026-02-17": "설날",
    "2026-09-25": "추석",
    "2027-02-06": "설날",
    "2027-09-15": "추석",
    "2028-01-27": "설날",
    "2028-10-03": "추석",
    "2026-03-01": "삼일절",
    "2026-05-05": "어린이날",
    "2026-06-06": "현충일",
    "2026-08-15": "광복절",
    "2026-10-03": "개천절",
    "2026-10-09": "한글날",
    "2026-12-25": "성탄절",
    "2027-03-01": "삼일절",
    "2027-05-05": "어린이날",
    "2027-08-15": "광복절",
    "2027-12-25": "성탄절",
}


def upcoming(today: dt.date, limit: int = 6) -> List[str]:
    """오늘 이후 명절 목록을 '2027-02-06 (설날, 토요일)' 형식으로 반환 (프롬프트 주입용)."""
    rows = []
    for iso, name in sorted(HOLIDAYS.items()):
        d = dt.date.fromisoformat(iso)
        if d < today:
            continue
        weekday = "월화수목금토일"[d.weekday()]
        rows.append(f"{iso} ({name}, {weekday}요일)")
        if len(rows) >= limit:
            break
    return rows
